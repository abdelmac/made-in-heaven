import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function isDirectory(path) {
  try {
    return Boolean(path) && statSync(path).isDirectory();
  } catch {
    return false;
  }
}

function environmentPath(value) {
  return value?.trim().replace(/^"(.*)"$/, '$1') || '';
}

function javaVersion(command) {
  const result = spawnSync(command, ['-version'], { encoding: 'utf8', timeout: 10_000 });
  const text = `${result.stdout || ''}\n${result.stderr || ''}`;
  const version = text.match(/(?:openjdk|java) version "([^"]+)"/)?.[1];
  const major = version?.startsWith('1.')
    ? Number(version.split('.')[1])
    : Number(version?.split('.')[0]);
  return { version, major: Number.isFinite(major) ? major : 0, usable: result.status === 0 };
}

/** Discover tools without changing the machine's environment or reading app secrets. */
export function findAndroidTools(
  root = projectRoot,
  env = process.env,
  platform = process.platform,
) {
  const portableRoot = join(root, '.local', 'mobile-tools');
  const portableJdks = isDirectory(portableRoot)
    ? readdirSync(portableRoot)
        .filter((name) => name.startsWith('jdk-'))
        .sort()
        .reverse()
        .map((name) => join(portableRoot, name))
    : [];
  const javaName = platform === 'win32' ? 'java.exe' : 'java';
  const studioJdk =
    platform === 'win32'
      ? 'C:/Program Files/Android/Android Studio/jbr'
      : platform === 'darwin'
        ? '/Applications/Android Studio.app/Contents/jbr/Contents/Home'
        : '/opt/android-studio/jbr';
  const homes = [environmentPath(env.JAVA_HOME), ...portableJdks, studioJdk].filter(Boolean);
  let javaHome = '';
  let javaCommand = 'java';
  let java = { version: undefined, major: 0, usable: false };
  for (const home of homes) {
    const command = join(home, 'bin', javaName);
    if (!existsSync(command)) continue;
    const candidate = javaVersion(command);
    if (candidate.usable && candidate.major >= 21) {
      javaHome = resolve(home);
      javaCommand = command;
      java = candidate;
      break;
    }
  }
  if (!java.usable) java = javaVersion(javaCommand);

  const sdkCandidates = [
    environmentPath(env.ANDROID_HOME),
    environmentPath(env.ANDROID_SDK_ROOT),
    join(portableRoot, 'android-sdk'),
    ...(platform === 'win32' && env.LOCALAPPDATA ? [join(env.LOCALAPPDATA, 'Android', 'Sdk')] : []),
    ...(platform === 'darwin' && env.HOME ? [join(env.HOME, 'Library', 'Android', 'sdk')] : []),
  ].filter(Boolean);
  const sdkRoot = sdkCandidates.find(isDirectory) || sdkCandidates[0] || '';
  return {
    javaHome,
    javaCommand,
    java,
    sdkRoot: sdkRoot ? resolve(sdkRoot) : '',
    platformJar: sdkRoot ? join(sdkRoot, 'platforms', 'android-36', 'android.jar') : '',
    buildTools: sdkRoot ? join(sdkRoot, 'build-tools', '36.0.0') : '',
    adb: sdkRoot ? join(sdkRoot, 'platform-tools', platform === 'win32' ? 'adb.exe' : 'adb') : '',
  };
}

export function collectMobileChecks(root = projectRoot, env = process.env) {
  const tools = findAndroidTools(root, env);
  const [nodeMajor, nodeMinor] = process.versions.node.split('.').map(Number);
  const nodeSupported =
    (nodeMajor === 22 && nodeMinor >= 13) || nodeMajor === 24 || nodeMajor >= 26;
  const packageVersion = (name) => {
    try {
      return JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'))
        .version;
    } catch {
      return null;
    }
  };
  const capacitorVersion = packageVersion('@capacitor/core');
  const rows = [
    { label: 'Node.js', ok: nodeSupported, required: true, detail: process.versions.node },
    {
      label: 'Capacitor runtime',
      ok: Boolean(capacitorVersion),
      required: true,
      detail: capacitorVersion || 'Run npm ci.',
    },
    {
      label: 'Capacitor configuration',
      ok: existsSync(join(root, 'capacitor.config.ts')),
      required: true,
      detail: 'capacitor.config.ts — com.solace.pomodoro',
    },
    {
      label: 'Bundled mobile interface',
      ok: existsSync(join(root, 'mobile', 'dist', 'index.html')),
      required: false,
      detail: 'mobile/dist/index.html — generated by npm run mobile:build',
    },
    {
      label: 'Android project and Gradle wrapper',
      ok:
        existsSync(join(root, 'android', 'app', 'build.gradle')) &&
        existsSync(join(root, 'android', 'gradle', 'wrapper', 'gradle-wrapper.jar')),
      required: true,
      detail: 'android/',
    },
    {
      label: 'iOS project',
      ok: existsSync(join(root, 'ios', 'App', 'App.xcodeproj', 'project.pbxproj')),
      required: false,
      detail: 'ios/App/App.xcodeproj',
    },
    {
      label: 'JDK 21 or later',
      ok: tools.java.usable && tools.java.major >= 21,
      required: true,
      detail: tools.java.version
        ? `${tools.java.version}${tools.javaHome ? ` — ${tools.javaHome}` : ' — PATH'}`
        : 'Set JAVA_HOME or install the portable tools.',
    },
    {
      label: 'Android SDK platform 36',
      ok: Boolean(tools.platformJar) && existsSync(tools.platformJar),
      required: true,
      detail: tools.sdkRoot || 'Set ANDROID_HOME or install the portable tools.',
    },
    {
      label: 'Android build-tools 36.0.0',
      ok: Boolean(tools.buildTools) && isDirectory(tools.buildTools),
      required: true,
      detail: tools.buildTools || 'Install build-tools;36.0.0 with Android SDK Manager.',
    },
    {
      label: 'Android device tools',
      ok: Boolean(tools.adb) && existsSync(tools.adb),
      required: false,
      detail: tools.adb || 'Install platform-tools to connect a test phone.',
    },
  ];
  if (process.platform === 'darwin') {
    const xcode = spawnSync('xcodebuild', ['-version'], { encoding: 'utf8', timeout: 10_000 });
    const xcodeMajor = Number(xcode.stdout?.match(/^Xcode (\d+)/m)?.[1]);
    rows.push({
      label: 'iOS compilation',
      ok: xcode.status === 0 && xcodeMajor >= 26,
      required: false,
      detail:
        xcode.status === 0
          ? xcode.stdout.trim().replace(/\n/g, ' — ')
          : 'Install Xcode 26 or later.',
    });
  } else {
    rows.push({
      label: 'iOS compilation',
      ok: false,
      required: false,
      detail: 'Requires macOS and Xcode 26 or later; this does not block Android builds.',
    });
  }
  return { tools, rows, ready: rows.every((row) => !row.required || row.ok) };
}

export function printMobileChecks(checks = collectMobileChecks()) {
  console.log('Solace mobile build environment');
  for (const row of checks.rows) {
    const status = row.ok ? 'OK' : row.required ? 'MISSING' : 'INFO';
    console.log(`[${status}] ${row.label}: ${row.detail}`);
  }
  console.log(
    checks.ready
      ? 'Android build prerequisites are available. Run npm run mobile:apk to compile the debug APK.'
      : 'Install the missing Android prerequisites, then run npm run mobile:doctor again. See docs/mobile.md.',
  );
  return checks;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = printMobileChecks().ready ? 0 : 1;
}
